export function getInstitutionById(id?: string | null): BankInstitution | undefined {
  if (!id) return undefined;
  return SUPPORTED_INSTITUTIONS.find((inst) => inst.id.toLowerCase() === id.toLowerCase());
}

export function getInstitutionsByRegion(region: "all" | "sea" | "global" | "us"): BankInstitution[] {
  if (region === "all") return SUPPORTED_INSTITUTIONS;
  if (region === "sea") {
    return SUPPORTED_INSTITUTIONS.filter((i) =>
      ["KH", "SG", "VN", "MY", "ID", "PH"].includes(i.country)
    );
  }
  if (region === "us") {
    return SUPPORTED_INSTITUTIONS.filter((i) => i.country === "US");
  }
  return SUPPORTED_INSTITUTIONS.filter((i) => ["GLOBAL", "UK"].includes(i.country));
}
